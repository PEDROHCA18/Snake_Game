void animation_custom(int matrix[5][5][3]){
    for (size_t i = 0; i <5; i++)
    {
        for (size_t j = 0; j < 5; j++)
        {
            if(i%2 == 0){
                set_pixel_color(1,matrix[4-i][4-j][1],matrix[4-i][4-j][0], matrix[4-i][4-j][2] );
            }else{
                set_pixel_color(1,matrix[4-i][j][1],matrix[4-i][j][0], matrix[4-i][j][2] );
            }
            
        }
    }
}


void smile(){
    //BOCA
    set_pixel_color(1,0,0,0);
    for(int i = 0 ; i <3; i ++){
        set_pixel_color(1,1,0,0);
    }
    set_pixel_color(1,0,0,0);

    set_pixel_color(1,1,0,0);
    for(int i = 0 ; i <3; i ++){
        set_pixel_color(1,0,0,0);
    }
    set_pixel_color(1,1,0,0);
    
    //espaço entre olho e boca

    for(int i = 0 ; i <5; i ++){
        set_pixel_color(1,0,0,0);
    }
    //OLHOS
    for(int j = 0;j<1;j++){
        for(int i = 0; i < 5 ; i++){
            i%2 == 0 ? set_pixel_color(1,0,0,0):set_pixel_color(1,1,0,0);
        }
    }
    //testa
    for(int i = 0 ; i <5; i ++){
        set_pixel_color(1,0,0,0);
    }
}

